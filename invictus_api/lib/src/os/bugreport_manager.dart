import 'package:plugin_platform_interface/plugin_platform_interface.dart';

import 'bugreport_params.dart';
import 'parcel_file_descriptor.dart';

/// Error codes that can be reported by [BugreportManager$BugreportCallback].
enum BugreportManager$BugreportCallback$ErrorCode {
  /// The input options were invalid. For example, the destination file the app provided
  /// could not be written by the system.
  invalidInput,

  /// A runtime error occurred.
  runtime,

  /// User denied consent to share the bugreport.
  userDeniedConsent,

  /// The request to get user consent timed out.
  userConsentTimedOut,

  /// There is currently a bugreport running. The caller should try again later.
  anotherReportInProgress,

  /// There is no bugreport to retrieve for the caller.
  noBugreportToRetrieve,
}

/// An interface describing the callback for bugreport progress and status.
///
/// Callers will receive [onProgress] calls as the bugreport progresses, followed by a
/// terminal call to either [onFinished] or [onError].
///
/// If an issue is encountered while starting the bugreport asynchronously, callers will
/// receive an [onError] call without any [onProgress] callbacks.
abstract interface class BugreportManager$BugreportCallback {
  /// Constructs a [BugreportManager$BugreportCallback].
  ///
  /// [onProgress] called when there is a progress update; the progress is in
  /// [0.0, 100.0].
  ///
  /// [onError] called when taking bugreport resulted in an error.
  ///
  /// If [BugreportManager$BugreportCallback$ErrorCode.userDeniedConsent] is passed, then
  /// the user did not consent to sharing the bugreport with the calling app.
  ///
  /// If [BugreportManager$BugreportCallback$ErrorCode.userConsentTimedOut] is passed,
  /// then the consent timed out, but the bugreport could be available in the internal
  /// directory of dumpstate for manual retrieval.
  ///
  /// If [BugreportManager$BugreportCallback$ErrorCode.anotherReportInProgress] is passed,
  /// then the caller should try later, as only one bugreport can be in progress at a
  /// time.
  ///
  /// [onFinished] called when taking bugreport finishes successfully.
  ///
  /// This callback will be invoked if the [BugreportParams$Flag.deferConsent] flag is not
  /// set.
  ///
  /// [onFinished$1] called when taking bugreport finishes successfully, with the absolute
  /// path of the generated bugreport file.
  ///
  /// This callback will only be invoked if the [BugreportParams$Flag.deferConsent] flag is
  /// set. Otherwise, the [onFinished] callback will be invoked.
  ///
  /// [onEarlyReportFinished] called when it is ready for calling app to show UI, showing
  /// any extra UI before this callback can interfere with bugreport generation.
  ///
  /// The returned callback can be passed to every [BugreportManager] method that accepts
  /// a [BugreportManager$BugreportCallback], including [BugreportManager.startBugreport],
  /// [BugreportManager.retrieveBugreport] and
  /// [BugreportManager.startConnectivityBugreport].
  factory BugreportManager$BugreportCallback({
    void Function(double progress)? onProgress,
    void Function(BugreportManager$BugreportCallback$ErrorCode errorCode)?
    onError,
    void Function()? onFinished,
    void Function(String bugreportFile)? onFinished$1,
    void Function()? onEarlyReportFinished,
  }) => BugreportManagerChannel.instance.createBugreportCallback(
    onProgress: onProgress,
    onError: onError,
    onFinished: onFinished,
    onFinished$1: onFinished$1,
    onEarlyReportFinished: onEarlyReportFinished,
  );
}

/// Class that provides a privileged API to capture and consume bugreports.
///
/// This class may only be used by apps that currently have carrier privileges (see
/// `android.telephony.TelephonyManager#hasCarrierPrivileges`) on an active SIM or
/// priv-apps explicitly allowed by the device manufacturer.
///
/// Only one bugreport can be generated by the system at a time.
abstract interface class BugreportManager {
  factory BugreportManager() => BugreportManagerChannel.instance.create();

  /// Cancels the currently running bugreport.
  ///
  /// Apps are only able to cancel their own bugreports. App A cannot cancel a bugreport
  /// started by app B.
  ///
  /// Requires the `android.Manifest.permission.DUMP` permission or that the calling app
  /// has carrier privileges (see `android.telephony.TelephonyManager#hasCarrierPrivileges`)
  /// on any active subscription.
  ///
  /// throws SecurityException if trying to cancel another app's bugreport in progress.
  void cancelBugreport();

  /// Speculatively pre-dumps UI data for a bugreport request that might come later.
  ///
  /// Triggers the dump of certain critical UI data, e.g. traces stored in short
  /// ring buffers that might get lost by the time the actual bugreport is requested.
  ///
  /// [BugreportManager.startBugreport] will then pick the pre-dumped data if both of the
  /// following conditions are met:
  /// - [BugreportParams$Flag.usePredumpedUiData] is specified.
  /// - [preDumpUiData] and [startBugreport] were called by the same UID.
  ///
  /// Requires the `android.Manifest.permission.DUMP` permission.
  void preDumpUiData();

  /// Requests a bugreport.
  ///
  /// This requests the platform/system to take a bugreport and makes the final bugreport
  /// available to the user. The user may choose to share it with another app, but the
  /// bugreport is never given back directly to the app that requested it.
  ///
  /// [params] [BugreportParams] that specify what kind of a bugreport should be taken,
  /// please note that not all kinds of bugreport allow for a progress notification.
  ///
  /// [shareTitle] title on the final share notification.
  ///
  /// [shareDescription] description on the final share notification.
  ///
  /// Requires the `android.Manifest.permission.DUMP` permission.
  void requestBugreport({
    required BugreportParams params,
    String? shareTitle,
    String? shareDescription,
  });

  /// Retrieves a previously generated bugreport.
  ///
  /// The previously generated bugreport must have been generated by calling
  /// [startBugreport] with the [BugreportParams$Flag.deferConsent] flag set. The
  /// bugreport file returned by the `onFinished(String)` callback of
  /// [BugreportManager$BugreportCallback] for a previously generated bugreport must be
  /// passed to this method. A caller may only retrieve bugreports that they have
  /// previously requested.
  ///
  /// The bugreport artifacts will be copied over to the given file descriptor only if the
  /// user consents to sharing with the calling app.
  ///
  /// [BugreportManager] takes ownership of [bugreportFd].
  ///
  /// The caller may only request to retrieve a given bugreport once. Subsequent calls
  /// will fail with error code
  /// [BugreportManager$BugreportCallback$ErrorCode.noBugreportToRetrieve].
  ///
  /// [bugreportFile] the identifier for a bugreport that was previously generated for this
  /// caller using [startBugreport].
  ///
  /// [bugreportFd] file to copy over the previous bugreport. This should be opened in
  /// write-only, append mode.
  ///
  /// [callback] callback for progress and status updates.
  ///
  /// Requires the `android.Manifest.permission.DUMP` permission.
  void retrieveBugreport({
    required String bugreportFile,
    required ParcelFileDescriptor bugreportFd,
    required BugreportManager$BugreportCallback callback,
  });

  /// Starts a bugreport.
  ///
  /// This starts a bugreport in the background. However the call itself can take several
  /// seconds to return in the worst case. [callback] will receive progress and status
  /// updates.
  ///
  /// The bugreport artifacts will be copied over to the given file descriptors only if
  /// the user consents to sharing with the calling app. If the
  /// [BugreportParams$Flag.deferConsent] flag is set, user consent will be deferred and
  /// no files will be copied to the given file descriptors.
  ///
  /// [BugreportManager] takes ownership of [bugreportFd] and [screenshotFd].
  ///
  /// [bugreportFd] file to write the bugreport. This should be opened in write-only,
  /// append mode.
  ///
  /// [screenshotFd] file to write the screenshot, if necessary. This should be opened in
  /// write-only, append mode.
  ///
  /// [params] options that specify what kind of a bugreport should be taken.
  ///
  /// [callback] callback for progress and status updates.
  ///
  /// Requires the `android.Manifest.permission.DUMP` permission.
  void startBugreport({
    required ParcelFileDescriptor bugreportFd,
    ParcelFileDescriptor? screenshotFd,
    required BugreportParams params,
    required BugreportManager$BugreportCallback callback,
  });

  /// Starts a connectivity bugreport.
  ///
  /// The connectivity bugreport is a specialized version of bugreport that only includes
  /// information specifically for debugging connectivity-related issues (e.g. telephony,
  /// wi-fi, and IP networking issues). It is intended primarily for use by OEMs and
  /// network providers such as mobile network operators. In addition to generally
  /// excluding information that isn't targeted to connectivity debugging, this type of
  /// bugreport excludes PII and sensitive information that isn't strictly necessary for
  /// connectivity debugging.
  ///
  /// The calling app MUST have a context-specific reason for requesting a connectivity
  /// bugreport, such as detecting a connectivity-related issue. This API SHALL NOT be used
  /// to perform random sampling from a fleet of public end-user devices.
  ///
  /// Calling this API will cause the system to ask the user for consent every single time.
  /// The bugreport artifacts will be copied over to the given file descriptors only if the
  /// user consents to sharing with the calling app.
  ///
  /// This starts a bugreport in the background. However the call itself can take several
  /// seconds to return in the worst case. [callback] will receive progress and status
  /// updates.
  ///
  /// Requires that the calling app has carrier privileges (see
  /// `android.telephony.TelephonyManager#hasCarrierPrivileges`) on any active subscription.
  ///
  /// [bugreportFd] file to write the bugreport. This should be opened in write-only,
  /// append mode.
  ///
  /// [callback] callback for progress and status updates.
  void startConnectivityBugreport({
    required ParcelFileDescriptor bugreportFd,
    required BugreportManager$BugreportCallback callback,
  });
}

abstract base class BugreportManagerChannel extends PlatformInterface {
  /// Constructs a [BugreportManagerChannel].
  BugreportManagerChannel() : super(token: _token);

  static final Object _token = Object();

  static BugreportManagerChannel? _instance;

  /// The default instance of [BugreportManagerChannel] to use.
  static BugreportManagerChannel get instance =>
      ArgumentError.checkNotNull(_instance, 'instance');

  /// Platform-specific implementations should set this with their own
  /// platform-specific class that extends [BugreportManagerChannel] when
  /// they register themselves.
  static set instance(BugreportManagerChannel instance) {
    PlatformInterface.verifyToken(instance, _token);
    _instance = instance;
  }

  BugreportManager create();

  BugreportManager$BugreportCallback createBugreportCallback({
    void Function(double progress)? onProgress,
    void Function(BugreportManager$BugreportCallback$ErrorCode errorCode)?
    onError,
    void Function()? onFinished,
    void Function(String bugreportFile)? onFinished$1,
    void Function()? onEarlyReportFinished,
  });
}
